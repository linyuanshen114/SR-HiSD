function s = onsager_initialize(logrho,V,level,opt,p)
U = onsager_constraint_basis(logrho,p);
V = onsager_orthogonalize(onsager_project(V,U,p.w),p.w);
[f,raw,energy] = onsager_force(logrho,U,p);
s = struct('level',level,'target',opt.target,'it',0,'initial_logrho',logrho, ...
    'logrho',logrho,'V',V,'Vp',zeros(p.N,opt.target), ...
    'Dx',zeros(p.N,1),'gp',zeros(p.N,1),'nf',onsager_wnorm(f,p.w), ...
    'raw_nf',onsager_wnorm(raw,p.w),'energy',energy,'beta',opt.dt, ...
    'history',zeros(0,7),'settings',{{}},'rng',rng);
end

