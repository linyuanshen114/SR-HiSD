function row=lb_trial_record(method,stage,order,sign,candidate,elapsed,verification_seconds)
%LB_TRIAL_RECORD One attempt, including failed signs, with separate timings.
row=struct('method',string(method),'stage',string(stage),'order',order,'sign',sign, ...
    'iterations',candidate.out.it,'residual',candidate.residual,'energy',candidate.energy, ...
    'coarse_index',candidate.index,'accepted',candidate.valid, ...
    'elapsed_seconds',elapsed,'kernel_seconds',candidate.out.solve_seconds, ...
    'verification_seconds',verification_seconds);
end
